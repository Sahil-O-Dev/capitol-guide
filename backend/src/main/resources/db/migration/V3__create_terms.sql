CREATE TABLE terms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_bioguide_id TEXT NOT NULL REFERENCES members (bioguide_id),
    chamber TEXT,
    congress INTEGER,
    district INTEGER,
    member_type TEXT,
    start_year INTEGER,
    end_year INTEGER,
    state_code TEXT,
    state_name TEXT
);

CREATE INDEX idx_terms_member_bioguide_id ON terms (member_bioguide_id);
