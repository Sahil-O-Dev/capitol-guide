CREATE TABLE party_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_bioguide_id TEXT NOT NULL REFERENCES members (bioguide_id),
    party_abbreviation TEXT,
    party_name TEXT,
    start_year INTEGER,
    end_year INTEGER
);

CREATE INDEX idx_party_history_member_bioguide_id ON party_history (member_bioguide_id);
